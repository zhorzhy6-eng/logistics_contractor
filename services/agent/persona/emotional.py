# -*- coding: utf-8 -*-
"""
Эмоциональная поддержка оператора (задание, часть 2).

Зачем модуль
------------
Оператор устаёт, злится и выгорает — это рабочая ситуация, а не сбой. Но
помощник, который на «устал от этого договора» отвечает «попейте чаю» или
начинает искать слово «устал» в базе, делает хуже. Здесь живёт РАСПОЗНАВАНИЕ
таких фраз и ГОТОВЫЙ блок правил, который подкладывается в запрос к модели.

Почему не только промпт. Промпт — это просьба, а не гарантия: модель может
её не выполнить (проверено на истории проекта: правило в промпте без
поддержки в коде исполнялось не всегда). Распознавание в коде работает
всегда, а текст блока остаётся в промпте — чтобы модель знала тон.

Что важно в тоне (B.2, B.3):
  * никаких советов «отдохните», «попейте чаю», «сделайте паузу»;
  * никаких нотаций и объяснений, что оператор неправ;
  * не извиняться по нескольку раз;
  * не переводить тему на работу сразу, если оператор о работе не говорит;
  * не использовать смайлики, если оператор их не использует.

Границы: модуль ничего не делает с формой и базой — только распознаёт
состояние и собирает текст правил.
"""

import logging
import re
from dataclasses import dataclass
from typing import Dict, List, Optional, Tuple

logger = logging.getLogger("core.agent.emotional")

# ─────────────────────────────────────────────────────────────
# Фразы-триггеры (A.1)
# ─────────────────────────────────────────────────────────────

#: Усталость и выгорание.
TIRED_PHRASES: Tuple[str, ...] = (
    "устал", "устала", "устали", "устаю", "уставший", "уставшая",
    "заколебал", "заколебало", "заколебали", "заколебалась",
    "надоел", "надоела", "надоело", "надоели",
    "не могу больше", "больше не могу", "сил нет", "сил больше нет",
    "нет сил", "выгораю", "выгорел", "выгорела", "вымотался", "вымоталась",
    "замучился", "замучилась", "задолбал", "задолбало", "задолбали",
    "достал", "достала", "достало", "достали", "как ты меня достал",
    "сколько можно", "задрал", "задрало", "задрали", "хватит",
    "я сдаюсь", "сдаюсь", "опустились руки", "руки опускаются",
    "терпение кончилось", "нет больше сил", "невыносимо",
)

#: Злость и раздражение.
ANGRY_PHRASES: Tuple[str, ...] = (
    "бесит", "бешусь", "бесит всё", "злит", "злюсь", "раздражает",
    "достало всё", "достало это", "надоело всё", "всё бесит",
    "заколебало всё", "ненавижу", "трясёт", "взбесило", "вывело",
    "как это терпеть", "сколько можно это терпеть",
)

#: Отчаяние: тут важнее всего не оставить человека одного с задачей.
DESPAIR_PHRASES: Tuple[str, ...] = (
    "не получается", "ничего не получается", "не выходит", "не работает",
    "всё сломалось", "все сломалось", "сломалось", "не могу",
    "бесполезно", "без толку", "я не справлюсь", "не справлюсь",
    "тупик", "застрял", "застряла", "помогите", "помоги",
)

#: Состояния: ключ → (название для лога, фразы).
STATE_PHRASES: Tuple[Tuple[str, str, Tuple[str, ...]], ...] = (
    ("tired", "усталость", TIRED_PHRASES),
    ("angry", "раздражение", ANGRY_PHRASES),
    ("despair", "отчаяние", DESPAIR_PHRASES),
)

#: Ключ состояния «оператор ругается» — считается отдельно (мат уже
#: обрабатывается промптом, но состояние то же: человеку плохо).
STATE_PROFANITY = "profanity"

#: Смайлики: если оператор их не пишет, помощник тоже не должен (B.3).
EMOJI_RE = re.compile(
    "[\U0001F300-\U0001FAFF\u2600-\u27BF\u2190-\u21FF\u2B00-\u2BFF]"
)

#: Вежливая просьба — не эмоция, а обычная работа.
_NEUTRAL_RE = re.compile(
    r"(пожалуйста|будь добр|будьте добры|если не сложно)", re.IGNORECASE
)

#: Слова-команды, которые стоят в начале рабочей просьбы: «устал, найди…»
#: — это и усталость, и поручение одновременно.
_WORK_VERBS = (
    "найди", "найти", "заполни", "заполнить", "покажи", "показать",
    "сверь", "сверить", "проверь", "проверить", "посчитай", "посчитать",
    "создай", "создать", "открой", "открыть", "подтяни", "подтянуть",
    "сравни", "сравнить", "посмотри", "посмотреть", "уточни", "уточнить",
)


@dataclass
class EmotionalState:
    """
    Что услышал помощник в сообщении оператора.

    :param states: какие состояния найдены (tired, angry, despair, profanity);
    :param phrases: фразы, по которым состояние найдено (для лога и тестов);
    :param uses_emoji: оператор сам использует смайлики (B.3);
    :param has_work: в сообщении есть рабочая просьба («устал, найди Ромашку»).
    """

    states: List[str]
    phrases: List[str]
    uses_emoji: bool
    has_work: bool

    @property
    def is_emotional(self) -> bool:
        """Есть ли вообще эмоция, на которую нужно отреагировать."""
        return bool(self.states)

    @property
    def needs_support(self) -> bool:
        """
        Нужна ли поддержка БЕЗ работы.

        Если оператор заодно дал поручение («устал, найди Ромашку»), работу
        делаем, но начинаем с одной фразы признания — не с нотации.
        """
        return self.is_emotional and not self.has_work

    def titles(self) -> List[str]:
        """Названия состояний (для лога: без текста сообщения)."""
        return [TITLES.get(state, state) for state in self.states]

    def to_dict(self) -> Dict[str, object]:
        """Состояние словарём — для тестов и журнала."""
        return {
            "states": list(self.states),
            "titles": self.titles(),
            "phrases": list(self.phrases),
            "uses_emoji": self.uses_emoji,
            "has_work": self.has_work,
        }


#: Названия состояний (в лог и в отчёт идут только они).
TITLES: Dict[str, str] = {
    "tired": "усталость",
    "angry": "раздражение",
    "despair": "отчаяние",
    STATE_PROFANITY: "ругается",
}


def _normalized(text: str) -> str:
    """Текст для поиска фраз: нижний регистр, ё → е, лишние пробелы убраны."""
    lowered = str(text or "").casefold().replace("ё", "е")
    return " ".join(lowered.split())


def detect(message: str) -> EmotionalState:
    """
    Распознаёт состояние оператора по его сообщению (A.1).

    Состояния складываются: «устал, всё бесит» — это и усталость, и
    раздражение. Фраза ищется как подстрока, поэтому «заколебало всё это»
    ловится по «заколебало».
    """
    text = _normalized(message)
    states: List[str] = []
    phrases: List[str] = []

    if text:
        for key, _title, phrases_list in STATE_PHRASES:
            for phrase in phrases_list:
                if phrase in text:
                    if key not in states:
                        states.append(key)
                    if phrase not in phrases:
                        phrases.append(phrase)
                    break

        from core.agent.words import PROFANITY_WORDS

        for word in PROFANITY_WORDS:
            if word in text:
                if STATE_PROFANITY not in states:
                    states.append(STATE_PROFANITY)
                if word not in phrases:
                    phrases.append(word)
                break

    return EmotionalState(
        states=states,
        phrases=phrases,
        uses_emoji=bool(EMOJI_RE.search(str(message or ""))),
        has_work=_has_work(text),
    )


def _has_work(text: str) -> bool:
    """Есть ли в сообщении рабочая просьба (команда из списка)."""
    if not text:
        return False
    return any(
        re.search(rf"(?<![а-яa-z]){verb}", text) for verb in _WORK_VERBS
    )


def support_block(state: EmotionalState) -> str:
    """
    Блок правил для модели — подкладывается в системный промпт (B.1).

    Возвращается пустая строка, если оператор спокоен: тогда блок только
    сбивал бы модель.
    """
    if not state.is_emotional:
        return ""

    lines: List[str] = [
        "СОСТОЯНИЕ ОПЕРАТОРА: " + ", ".join(state.titles()) + ".",
        "Ответь коротко и по-человечески. Правила:",
        "- признай состояние одной фразой («Понимаю», «Слышу», «Стоп, давай "
        "по одной задаче») — без оценки и без «вы устали, потому что…»;",
        "- НЕ давай советов отдохнуть, попить чаю, сделать паузу, "
        "подышать, размяться;",
        "- НЕ читай нотаций и не объясняй, что оператор делает не так;",
        "- НЕ извиняйся больше одного раза;",
        "- НЕ переводи тему на работу, если оператор о работе не говорил.",
    ]

    if state.has_work:
        lines.append(
            "- В сообщении есть поручение: сделай работу и начни ответ с "
            "одной короткой фразы признания, дальше — по делу."
        )
    elif "tired" in state.states:
        lines.append(
            "- Предложи конкретную помощь по открытой форме: «Могу взять на "
            "себя заполнение…» — и назови, что именно."
        )
    elif "angry" in state.states:
        lines.append(
            "- Спроси, что именно не так (программа, данные, клиент), и "
            "предложи проверить это вместе. Не оправдывайся."
        )
    elif "despair" in state.states:
        lines.append(
            "- Разбей задачу на один следующий шаг: «Давай по одной задаче. "
            "Что сейчас самое срочное?»"
        )

    if STATE_PROFANITY in state.states:
        lines.append(
            "- Оператор ругается: не повторяй ругательства, не ищи их в "
            "базе, не обижайся. Коротко: «Понял. Что не так? Исправлю.»"
        )

    if state.uses_emoji:
        lines.append("- Смайлики уместны: оператор их использует.")
    else:
        lines.append("- Смайлики НЕ используй: оператор их не пишет.")

    return "\n".join(lines)


def is_emotional(message: str) -> bool:
    """Короткая проверка «в сообщении есть эмоция» (для тестов и вызовов)."""
    return detect(message).is_emotional


def emotional_block(message: str) -> Tuple[str, Optional[EmotionalState]]:
    """
    Блок правил и состояние одним вызовом (так его зовёт Agent.send).

    :return: ``(текст блока, состояние)``; блок пуст, если оператор спокоен.
    """
    state = detect(message)
    if not state.is_emotional:
        return "", None
    logger.info(
        "Эмоциональная поддержка: состояния=%s, поручение=%s",
        state.titles(), state.has_work,
    )
    return support_block(state), state


