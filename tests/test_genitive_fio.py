# ─────────────────────────────────────────────────────────────
# Границы: два слова, одно слово, пусто
# ─────────────────────────────────────────────────────────────

def test_two_words_only():
    """Два слова — фамилия и имя, без отчества."""
    assert genitive_fio("Иванов Пётр") == "Иванова Пётра"


def test_two_words_female():
    """Род в этом случае берётся не из отчества, а из аргумента."""
    assert genitive_fio("Иванова Мария", gender="female") == "Ивановой Марии"


def test_one_word_only_male():
    """Одно слово — только фамилия; род определяет форму."""
    assert genitive_fio("Иванов") == "Иванова"
    assert genitive_fio("Хейгетян") == "Хейгетян"


def test_one_word_only_female():
    """Женская фамилия без имени: «Иванова» → «Ивановой»."""
    assert genitive_fio("Иванова", gender="female") == "Ивановой"


def test_empty_returns_empty():
    """Пустое значение — пустая строка: в бланке не появится «None»."""
    assert genitive_fio("") == ""
    assert genitive_fio("   ") == ""
    assert genitive_fio(None) == ""


def test_ip_prefix_stripped():
    """Приставка «ИП» в падеж не попадает и не ломает разбор слов."""
    assert genitive_fio(
        "Индивидуальный предприниматель Смирнова Елена Владимировна"
    ) == "Смирновой Елены Владимировны"
    assert genitive_fio("ИП Смирнов Алексей Николаевич") == \
        "Смирнова Алексея Николаевича"


def test_gender_detected_inside():
    """Род не передан — берётся из отчества (женщина склоняется как женщина).

    «Иванова Мария Ивановна» без подсказки рода: фамилия на «-ова»
    склоняется как ЖЕНСКАЯ. Если бы род не определялся, вышло бы
    «Иванова Марии Ивановны».
    """
    assert detect_gender("Иванова Мария Ивановна") == "female"
    assert genitive_fio("Иванова Мария Ивановна") == \
        "Ивановой Марии Ивановны"


def test_tail_words_are_kept():
    """Четвёртое и дальше слово — не имя, а пометка: остаётся как есть."""
    assert genitive_fio("Иванов Иван Иванович (врио)") == \
        "Иванова Ивана Ивановича (врио)"


@pytest.mark.parametrize("full_name,expected", [
    ("Ахмедов Тимур Артурович", "Ахмедова Тимура Артуровича"),
    ("Иванова Мария Ивановна", "Ивановой Марии Ивановны"),
    ("Хейгетян Елена Валентиновна", "Хейгетян Елены Валентиновны"),
    ("Шевченко Ольга Ивановна", "Шевченко Ольги Ивановны"),
    ("Сидорова Анна Петровна", "Сидоровой Анны Петровны"),
    ("Пестряев Алексей Николаевич", "Пестряева Алексея Николаевича"),
    ("Добросоцкий Алексей Николаевич", "Добросоцкого Алексея Николаевича"),
    ("Иванов-Петров Иван Иванович", "Иванова-Петрова Ивана Ивановича"),
])
def test_acceptance_examples(full_name, expected):
    """Примеры из критериев приёмки шага — одной таблицей."""
    assert genitive_fio(full_name) == expected
