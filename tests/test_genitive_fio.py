def test_yan_not_inflected():
    """«-ян» (Хейгетян): фамилия не склоняется, имя и отчество — да."""
    assert genitive_fio("Хейгетян Елена Валентиновна") == \
        "Хейгетян Елены Валентиновны"


def test_yan_not_inflected_male():
    """У мужчины та же фамилия тоже остаётся как есть."""
    assert genitive_fio("Хейгетян Артур Валентинович") == \
        "Хейгетян Артура Валентиновича"


def test_enko_not_inflected():
    """«-енко» (Шевченко) не склоняется ни у кого."""
