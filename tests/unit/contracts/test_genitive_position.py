#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Должность в родительном падеже (ШАГ «Полные стороны + склонение с учётом рода»).

Что было
--------
П. 1.1 и 1.2 бланка печатали должность в ИМЕНИТЕЛЬНОМ падеже: «в лице
Генеральный директор Петров Пётр Петрович». Нужно «в лице генерального
директора Петрова Петра Петровича» — падеж считает генератор, в одном месте,
а не три бланка по-своему.

Правило перенесено из аренды ТС (`core/contracts/arenda_ts/generator.py`,
`_genitive_position`): разбор по окончаниям, морфологического словаря в
проекте нет. Слово, уже стоящее в родительном падеже, не трогается.

Данные синтетические, ПДн нет.
"""

import pytest

from core.contracts.ru_morphology import genitive_position


@pytest.mark.parametrize("position,expected", [
    ("Директор", "Директора"),
    ("директор", "директора"),
    ("Генеральный директор", "Генерального директора"),
    ("Финансовый директор", "Финансового директора"),
    ("Главный инженер", "Главного инженера"),
    ("Управляющий", "Управляющего"),
    ("Заместитель директора", "Заместитель директора"),
    ("Председатель", "Председателя"),
    ("Исполнительный директор", "Исполнительного директора"),
])
def test_genitive_position(position, expected):
    """
    Должность в родительном падеже.

    «Управляющий» — субстантивированное прилагательное: «-щий» → «-щего».
    В аренде ТС то же слово давало «Управляющого» (общее правило «-ий →
    -ого»); в общем модуле случай закрыт отдельно, потому что «Управляющий»
    в справочнике встречается, а «Управляющого» по-русски не существует.
    """
    assert genitive_position(position) == expected


def test_ip_position_not_inflected():
    """«Индивидуальный предприниматель» склоняется штатно (ИП действует сам)."""
    assert genitive_position("Индивидуальный предприниматель") == \
        "Индивидуального предпринимателя"


def test_abbreviation_is_not_inflected():
    """
    Сокращения из заглавных букв не склоняются, даже если стоят последними.

    У должности падеж несёт последнее слово, но у сокращения падежа нет:
    «Заместитель ИП» остаётся как есть, а «Заместитель директора» — тоже
    (существительное уже в родительном падеже, окончание «-а»).
    """
    assert genitive_position("ИП") == "ИП"
    assert genitive_position("Заместитель ИП") == "Заместитель ИП"
    assert genitive_position("Главный инженер") == "Главного инженера"


def test_empty_returns_empty():
    """Пустая должность — пустая строка, без «None»."""
    assert genitive_position("") == ""
    assert genitive_position("   ") == ""
    assert genitive_position(None) == ""


def test_already_genitive_is_kept():
    """Должность уже в родительном падеже — второй раз не склоняется."""
    assert genitive_position("директора") == "директора"
    assert genitive_position("Генерального директора") == \
        "Генерального директора"


def test_female_adjective():
    """Женское прилагательное в должности: «-ая» → «-ой»."""
    assert genitive_position("Финансовая директор") == "Финансовой директора"
