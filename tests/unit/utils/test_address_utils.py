#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Правило отделения наименования салона от адреса.

Проверяется core.utils.address_utils.split_salon_name — ОДНО правило на
импорт справочника салонов, авто-загрузку и любой другой импорт адресов:

  * точный хвост, совпадающий с колонкой «Наименование»;
  * хвост с организационно-правовой формой (ООО, АО, ПАО, …), когда
    колонка наименования пуста;
  * адрес и наименование, слипшиеся в один сегмент;
  * защита от ложных обрезаний: чистая строка не меняется, пустой адрес
    не возвращается, середина слова не режется.

Все данные синтетические или взяты из делового справочника салонов:
ФИО, телефонов и почты здесь нет.
"""

import pytest

from core.utils.address_utils import split_salon_name


#: (адрес с наименованием в хвосте, колонка «Наименование», чистый адрес).
EXACT_TAIL_CASES = [
    (
        "Нижневартовск, Мира, владение 3/п, строение 11, "
        "АВТОМАГ (Нижневартовск) ООО",
        "АВТОМАГ (Нижневартовск) ООО",
        "Нижневартовск, Мира, владение 3/п, строение 11",
    ),
    (
        "Сургут, Югорский тракт, дом № 23, сооружение 1, ВМ-С-АЗИЯ ООО",
        "ВМ-С-АЗИЯ ООО",
        "Сургут, Югорский тракт, дом № 23, сооружение 1",
    ),
    (
        'Сургут, Профсоюзов, дом № 1/3, ООО "СК-МОТОРС ПРЕМИУМ"',
        'ООО "СК-МОТОРС ПРЕМИУМ"',
        "Сургут, Профсоюзов, дом № 1/3",
    ),
]


@pytest.mark.parametrize("address, name, clean", EXACT_TAIL_CASES)
def test_exact_tail_is_cut(address, name, clean):
    """Хвост, совпавший с колонкой наименования, уходит из адреса."""
    assert split_salon_name(address, name) == (clean, name)


def test_quotes_and_case_do_not_matter():
    """Кавычки и регистр не мешают узнать хвост адреса."""
    address = 'Сургут, Профсоюзов, дом № 1/3, ООО "СК-МОТОРС ПРЕМИУМ"'
    name = "ООО «СК-МОТОРС ПРЕМИУМ»"

    assert split_salon_name(address, name) == (
        "Сургут, Профсоюзов, дом № 1/3",
        name,
    )


#: (адрес, чистый адрес, найденное наименование).
EXTRACT_CASES = [
    (
        "Сургут, Профсоюзов, дом № 1/3, ООО «Ромашка»",
        "Сургут, Профсоюзов, дом № 1/3",
        "ООО «Ромашка»",
    ),
    (
        "г. Москва, ул. Ленина, д. 5, строение 11 "
        "АВТОМАГ (Нижневартовск) ООО",
        "г. Москва, ул. Ленина, д. 5, строение 11",
        "АВТОМАГ (Нижневартовск) ООО",
    ),
    (
        "г. Москва, ул. Ленина, д. 5, д. 5 ООО «Ромашка»",
        "г. Москва, ул. Ленина, д. 5, д. 5",
        "ООО «Ромашка»",
    ),
    (
        "г. Москва, ул. Ленина, д. 5 АВТОМАГ ООО",
        "г. Москва, ул. Ленина, д. 5",
        "АВТОМАГ ООО",
    ),
]


@pytest.mark.parametrize("address, clean, name", EXTRACT_CASES)
def test_name_is_extracted_when_column_is_empty(address, clean, name):
    """Наименование находится в адресе, даже если колонка пуста."""
    assert split_salon_name(address, "") == (clean, name)


def test_clean_address_is_not_changed():
    """Адрес без хвоста остаётся ровно таким, каким пришёл."""
    address = (
        "Кировская область, г.о. город Киров, г. Киров, "
        "ул. Московская, д. 106а"
    )
    assert split_salon_name(address, 'АО "Моторавто"') == (
        address,
        'АО "Моторавто"',
    )


def test_column_name_wins_over_tail():
    """Если наименование есть в колонке, найденное в адресе его не заменяет."""
    address = "Сургут, Профсоюзов, дом № 1/3, ООО «Ромашка»"
    assert split_salon_name(address, "Другой салон") == (
        "Сургут, Профсоюзов, дом № 1/3",
        "Другой салон",
    )


def test_name_in_middle_is_not_cut():
    """Наименование в середине адреса не трогаем — режем только хвост."""
    address = "г. Москва, ООО «Ромашка», ул. Ленина, д. 5"
    assert split_salon_name(address, "ООО «Ромашка»") == (
        address,
        "ООО «Ромашка»",
    )


def test_address_without_org_form_is_not_cut():
    """«стр. 2» в конце — это адрес, а не наименование."""
    address = "г. Москва, ул. Ленина, д. 5, стр. 2"
    assert split_salon_name(address, 'ООО "Ромашка"') == (
        address,
        'ООО "Ромашка"',
    )


def test_partial_word_is_not_cut():
    """Хвост, начинающийся с середины слова, не отрезается."""
    address = "г. Москва, ул. Ленина, д. 5, АВТОМАГОВО"
    assert split_salon_name(address, "ГОВО") == (address, "ГОВО")


def test_short_name_does_not_leave_org_form_in_address():
    """Короткое имя из колонки не оставляет «ООО «» в адресе."""
    address = "Сургут, Профсоюзов, дом № 1/3, ООО «Ромашка»"

    assert split_salon_name(address, "Ромашка") == (
        "Сургут, Профсоюзов, дом № 1/3",
        "Ромашка",
    )


def test_name_only_address_is_not_emptied():
    """Если кроме наименования в адресе ничего нет, адрес не обнуляем."""
    assert split_salon_name("ООО «Ромашка»", "ООО «Ромашка»") == (
        "ООО «Ромашка»",
        "ООО «Ромашка»",
    )


@pytest.mark.parametrize(
    "address, name",
    [
        ("", ""),
        ("   ", ""),
        ("", "ООО «Ромашка»"),
        ("г. Москва, ул. Ленина, д. 5", ""),
    ],
)
def test_empty_inputs(address, name):
    """Пустые строки не превращаются в мусор."""
    clean, salon = split_salon_name(address, name)
    assert clean == address.strip()
    assert salon == name.strip()


@pytest.mark.parametrize("address, name, clean", EXACT_TAIL_CASES)
def test_idempotent(address, name, clean):
    """Повторная обработка уже чистого адреса ничего не меняет."""
    assert split_salon_name(clean, name) == (clean, name)
    assert split_salon_name(address, name) == (clean, name)
