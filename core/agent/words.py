#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Служебные слова диалога: команды, вопросы, вежливость, ругательства.

Зачем отдельный модуль
----------------------
Один и тот же список нужен в ДВУХ местах:

  * в промпте (``core/agent/prompt.py`` подставляет его в текст правил) —
    чтобы модель ЗНАЛА, какие слова не являются названиями, и не звала
    поиск с ними;
  * в инструментах поиска (``core/agent/tools.py``) — чтобы служебное
    слово не ушло в базу ДАЖЕ ЕСЛИ модель ошиблась.

Держать два списка — значит развести их через месяц: промпт будет
запрещать одно, а код пропускать другое. Поэтому список один и лежит
здесь, а оба потребителя берут его отсюда.

Правило разбора — не «слово из списка», а «в запросе НЕТ НИ ОДНОГО
названия». «Ромашка, покажи» — это запрос с названием, и искать его нужно;
«Отмени» — только команда, и искать в ней нечего.
"""

from typing import List, Tuple

#: Команды без объекта: глаголы, которые оператор говорит программе.
#: Искать их в базе как имена или названия бессмысленно.
COMMAND_WORDS: Tuple[str, ...] = (
    "заполни", "заполнить", "заполняй", "заполните",
    "найди", "найти", "найди-ка", "ищи", "поищи", "поищите", "искать",
    "покажи", "показать", "покажите", "выведи", "вывести",
    "отмени", "отменить", "отмените", "отмена",
    "сверь", "сверить", "сверьте", "сравни", "сравнить",
    "проверь", "проверить", "проверьте",
    "подтяни", "подтянуть", "поставь", "поставить", "вставь", "вставить",
    "сохрани", "сохранить", "запиши", "записать",
    "удали", "удалить", "очисти", "очистить", "сбрось", "сбросить",
    "открой", "открыть", "закрой", "закрыть", "сделай", "сделать",
)

#: Вопросы и вежливость: оператор спрашивает или здоровается.
QUESTION_WORDS: Tuple[str, ...] = (
    "сможешь", "смождешь", "сможишь", "можешь", "можеш", "можете",
    "умеешь", "умееш", "умеете", "получится", "сможется",
    "помоги", "помогите", "подскажи", "подскажите", "объясни", "объясните",
    "привет", "здравствуй", "здравствуйте", "добрый", "спасибо",
    "благодарю", "пожалуйста", "пока", "прощай", "давай", "давайте",
    "ок", "окей", "хорошо", "ага", "угу", "ладно",
)

#: Вопросительные слова: сами по себе они не название.
ASK_WORDS: Tuple[str, ...] = (
    "как", "что", "чем", "почему", "зачем", "где", "куда", "откуда",
    "когда", "кто", "кого", "кому", "сколько", "какой", "какая", "какое",
    "какие", "можно", "нужно", "надо",
)

#: Союзы, частицы, междометия: не название, даже если длиннее трёх букв.
FILLER_WORDS: Tuple[str, ...] = (
    "и", "а", "но", "да", "нет", "не", "ни", "ну", "же", "ли", "бы",
    "это", "то", "вот", "там", "тут", "здесь", "ещё", "еще", "уже",
    "тоже", "так", "ой", "ах", "эх", "мм", "эм", "блин",
)

#: Ругательства. Важна не полнота списка, а принцип: мат не ищется в базе
#: и не повторяется в ответе. Основа слова ловится целиком, поэтому
#: «заебал», «заебало» и «заебали» попадают в список по отдельности.
PROFANITY_WORDS: Tuple[str, ...] = (
    "блядь", "блять", "бля", "бляха", "хуй", "хуйня", "хуёво", "хуево",
    "пиздец", "пизда", "пизде", "ебать", "ебал", "ебала", "ебанутый",
    "ебаный", "ёбаный", "ебаться", "заебал", "заебала", "заебало",
    "заебали", "заебись", "сука", "суки", "нахер", "нахуй", "нах",
    "мразь", "тварь", "говно", "дерьмо", "херня", "хрен",
)

#: Всё служебное вместе — по нему работает и промпт, и проверка в коде.
NON_NAME_WORDS: frozenset = frozenset(
    COMMAND_WORDS + QUESTION_WORDS + ASK_WORDS + FILLER_WORDS + PROFANITY_WORDS
)

#: Группы для подстановки в промпт: (заголовок, слова).
PROMPT_GROUPS: Tuple[Tuple[str, Tuple[str, ...]], ...] = (
    ("команды без объекта", COMMAND_WORDS),
    ("вопросы и вежливость", QUESTION_WORDS),
    ("вопросительные слова", ASK_WORDS),
    ("союзы и частицы", FILLER_WORDS),
    ("ругательства", PROFANITY_WORDS),
)


def prompt_block() -> str:
    """
    Список служебных слов для подстановки в промпт.

    Печатается коротко и без пояснений: модели нужен перечень, по которому
    она узнаёт слово, а не рассказ о нём.
    """
    lines: List[str] = []
    for title, words in PROMPT_GROUPS:
        lines.append(f"- {title}: " + ", ".join(words))
    return "\n".join(lines)


__all__ = [
    "ASK_WORDS",
    "COMMAND_WORDS",
    "FILLER_WORDS",
    "NON_NAME_WORDS",
    "PROFANITY_WORDS",
    "PROMPT_GROUPS",
    "QUESTION_WORDS",
    "prompt_block",
]
