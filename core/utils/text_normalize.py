#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Нормализация ДОЛЖНОСТИ, пришедшей капсом («ДИРЕКТОР» → «Директор»).

Зачем отдельный модуль
----------------------
Внешние источники отдают должность руководителя в ВЕРХНЕМ РЕГИСТРЕ:

  * DaData: `data.management.post` = «ГЕНЕРАЛЬНЫЙ ДИРЕКТОР» — это их формат
    хранения поля, а не общепринятый;
  * выписки ЕГРЮЛ и карточки контрагентов: «ДИРЕКТОР»;
  * распознавание сканов: OCR часто теряет регистр и отдаёт строку целиком
    заглавными.

В документах принято «Директор», «Генеральный директор». Капс — не ошибка
данных, а ФОРМАТ источника, поэтому чинится он на входе (DaData, справочник),
а последний барьер — `core/contracts/ru_morphology.py::genitive_position`:
если капс всё-таки проскочил из справочника, в договор уйдёт «Директора»,
а не «ДИРЕКТОРА».

Правила одни и те же для всех входов, поэтому живут в одном месте: три
копии «привести к виду Первая заглавная» разъехались бы при первой правке.
Модуль без Qt, без docx и без базы — только работа со строкой.

Что НЕ трогается
----------------
  * НАИМЕНОВАНИЯ организаций: для них авторитетный источник — DaData (данные
    ЕГРЮЛ). Если у них «ООО "АВАТЭК"» капсом, значит, так и в реестре, и
    печатать «ООО "Аватэк"» нельзя — это уже другое наименование, а не
    оформление. Ни `save_organization`, ни `_parse_suggestion` наименования
    не нормализуют (см. `normalize_organization_fields`);
  * ФИО: регистр в именах значим («Иванов» ≠ «иванов»), поэтому ФИО не
    нормализуется вовсе;
  * сокращения: «ИП», «ООО», «АО» остаются как есть — у них капс это норма,
    а не формат источника;
  * значения в обычном регистре («Директор», «директор») — как есть.

Общая функция `normalize_caps_phrase` умеет и наименования (она понимает
кавычки и аббревиатуры), но к полям организации её применяет только тот, кто
осознанно этого хочет: по умолчанию — никто.
"""

from typing import Any, Dict

__all__ = [
    "ABBREVIATION_MAX_LENGTH",
    "SERVICE_WORDS",
    "SHORT_VALUE_MAX_LENGTH",
    "is_abbreviation",
    "is_all_caps",
    "normalize_caps_phrase",
    "normalize_organization_fields",
    "normalize_position",
]

#: Значение длиной не больше этого числа символов считается сокращением
#: («ИП», «ООО», «АО») и остаётся как есть. Служебные слова («по», «для»)
#: тоже короче — их защищает отдельный список.
SHORT_VALUE_MAX_LENGTH = 3

#: Аббревиатура внутри фразы: букв не больше этого числа, все заглавные
#: («ИП», «ООО», «АО», «ГУП»). Порог тот же, что у короткого значения, и по
#: той же причине: «ПАО» и «ИВАН» по написанию неразличимы, а
#: четырёхбуквенное слово в поле должности — скорее имя в капсе, чем
#: аббревиатура. Ошибка в эту сторону безопаснее: лишняя строчная буква
#: заметна и безобидна, лишний капс уходит в договор.
ABBREVIATION_MAX_LENGTH = SHORT_VALUE_MAX_LENGTH

#: Служебные слова должности и наименования: пишутся строчными
#: («Директор по развитию», «Общество с ограниченной ответственностью»).
SERVICE_WORDS = frozenset({
    "и", "в", "во", "на", "по", "с", "со", "у", "для", "из", "о", "об",
})

#: Кавычки, которыми в наименованиях выделяют название: «…», "…", „…“, “…”.
_OPENING_QUOTES = "«\"“„"
_CLOSING_QUOTES = "»\"“”"


def is_all_caps(value: Any) -> bool:
    """
    Значение целиком в верхнем регистре и длиннее сокращения?

    Пустая строка, «None» и короткие сокращения («ИП», «ООО») — не капс
    для целей нормализации: их трогать не нужно. Цифры и знаки
    препинания регистра не имеют и на ответ не влияют.
    """
    text = "" if value is None else str(value).strip()
    return len(text) > SHORT_VALUE_MAX_LENGTH and text.isupper()


def is_abbreviation(word: str) -> bool:
    """
    Слово — аббревиатура («ИП», «ООО», «АО», «ГУП»)?

    Признаки: все буквы заглавные, букв не меньше двух и не больше
    `ABBREVIATION_MAX_LENGTH`, дефиса в слове нет. Знаки вокруг слова
    не мешают («ООО» в кавычках — та же аббревиатура), а одиночная
    буква — инициал, а не аббревиатура: «Иванов И. И.» печатается с
    заглавных.

    Дефисное слово аббревиатурой не считается целиком: «ИП-ПЕТРОВ» —
    это «ИП» плюс фамилия, и нормализуется по частям.
    """
    text = str(word or "")
    if "-" in text:
        return False
    letters = [char for char in text if char.isalpha()]
    if not 2 <= len(letters) <= ABBREVIATION_MAX_LENGTH:
        return False
    return text.isupper()


def _quote_delta(word: str) -> int:
    """
    Насколько слово меняет «глубину кавычек».

    «ООО «РОМАШКА»» — открывающая кавычка в одном слове, закрывающая в
    другом; «(ООО «РОМАШКА»)» — всё в одном. Считается именно глубина, а не
    факт «есть кавычка»: иначе закрывающая кавычка открывала бы новую часть
    наименования.
    """
    depth = 0
    for char in word:
        if char in _OPENING_QUOTES:
            depth += 1
        elif char in _CLOSING_QUOTES:
            depth -= 1
    return depth


def _normalize_caps_token(token: str, capitalize: bool) -> str:
    """
    Одно слово капсом: аббревиатура — как есть, иначе строчные буквы.

    Заглавная ставится только тому слову, которое просит вызывающий
    (`capitalize=True` — первое содержательное слово части): должность и
    наименование пишутся с одной заглавной буквы, «Генеральный директор»,
    а не «Генеральный Директор».

    Пунктуация сохраняется и позицию не сдвигает: ««РОМАШКА»» →
    ««Ромашка»», «(ДИРЕКТОР)» → «(Директор)», «ДИРЕКТОР,» → «Директор,» —
    регистр меняется только у букв.

    Дефисное слово нормализуется по частям: «ДИРЕКТОР-РАСПОРЯДИТЕЛЬ» →
    «Директор-распорядитель», «ИП-ПЕТРОВ» → «ИП-Петров». Заглавную несёт
    слово целиком, поэтому вторая часть её не получает.
    """
    if is_abbreviation(token):
        return token

    parts = token.split("-")
    return "-".join(
        _normalize_caps_letters(part, capitalize=capitalize and index == 0)
        for index, part in enumerate(parts)
    )


def _normalize_caps_letters(part: str, capitalize: bool) -> str:
    """Буквы одной части слова: первая заглавная (если просят), остальные строчные."""
    letters = [index for index, char in enumerate(part) if char.isalpha()]
    if not letters:
        return part

    first = letters[0]
    result = []
    for index, char in enumerate(part):
        if not char.isalpha():
            result.append(char)
        elif index == first and capitalize:
            result.append(char.upper())
        else:
            result.append(char.lower())
    return "".join(result)


def normalize_caps_phrase(value: Any) -> str:
    """
    Строка капсом → обычный регистр.

    Правила:
      * заглавная буква — у первого СОДЕРЖАТЕЛЬНОГО слова части: вне
        кавычек и отдельно внутри каждой пары кавычек. «ГЕНЕРАЛЬНЫЙ
        ДИРЕКТОР» → «Генеральный директор»; «ОБЩЕСТВО С ОГРАНИЧЕННОЙ
        ОТВЕТСТВЕННОСТЬЮ «РОМАШКА»» → «Общество с ограниченной
        ответственностью «Ромашка»» — у названия в кавычках своя заглавная;
      * служебные слова (см. SERVICE_WORDS) всегда строчные и заглавную
        не перехватывают: «ДИРЕКТОР ПО РАЗВИТИЮ» → «Директор по развитию»,
        «ПО РАЗВИТИЮ» → «по Развитию» (со служебного слова должность не
        начинается — это обрывок, но регистр предсказуем);
      * аббревиатуры (см. `is_abbreviation`) не трогаются и заглавную тоже
        не перехватывают: «ООО «АВТОТРАНС»» → «ООО «Автотранс»»,
        «ООО РОМАШКА» → «ООО Ромашка»;
      * знаки препинания сохраняются, регистр меняется только у букв;
      * дефисное слово несёт одну заглавную: «ДИРЕКТОР-РАСПОРЯДИТЕЛЬ» →
        «Директор-распорядитель».

    Значение, не являющееся капсом, возвращается как есть (обрезанным по
    краям): «Директор» и «директор» не меняются.
    """
    text = "" if value is None else str(value).strip()
    if not is_all_caps(text):
        return text

    words = text.split()
    capitalize: set = set()
    lowercase: set = set()
    quote_depth = 0
    #: Начало части: её первое содержательное слово получает заглавную.
    #: Части разделяют кавычки — в «ООО «РОМАШКА»» их две, и заглавная нужна
    #: обеим («ООО «Ромашка»»), иначе название в кавычках вышло бы строчным.
    region_start = True

    for index, word in enumerate(words):
        inside_quotes = quote_depth > 0
        if word[:1] in _OPENING_QUOTES and not inside_quotes:
            region_start = True

        if not any(char.isalpha() for char in word):
            # Знак препинания отдельным словом: регистр не меняется и
            # начала части не «съедает».
            pass
        elif word.lower() in SERVICE_WORDS:
            # Служебное слово строчное всегда — и в начале части тоже
            # («ПО РАЗВИТИЮ» → «по Развитию»: должность со служебного слова
            # не начинается, это обрывок, и заглавную несёт первое
            # содержательное слово). Заглавную оно не перехватывает.
            lowercase.add(index)
        elif is_abbreviation(word):
            # Аббревиатура («ИП», «ООО») не трогается и заглавную не
            # перехватывает: без этого «ООО РОМАШКА» → «ООО ромашка».
            pass
        elif region_start:
            capitalize.add(index)
            region_start = False
        else:
            region_start = False

        quote_depth += _quote_delta(word)

    result = []
    for index, word in enumerate(words):
        if index in lowercase:
            result.append(word.lower())
            continue
        if word.lower() in SERVICE_WORDS:
            result.append(word.capitalize() if index in capitalize else word.lower())
            continue
        result.append(_normalize_caps_token(word, capitalize=index in capitalize))
    return " ".join(result)


def normalize_position(value: Any) -> str:
    """
    Должность капсом → обычный регистр.

    «ГЕНЕРАЛЬНЫЙ ДИРЕКТОР» → «Генеральный директор», «ДИРЕКТОР» →
    «Директор», «ДИРЕКТОР ПО РАЗВИТИЮ» → «Директор по развитию».
    Сокращения («ИП», «ООО») не трогаются.

    Это ЕДИНСТВЕННОЕ поле организации, которое нормализуется: у наименования
    капс — данные реестра, а не формат источника (см. `normalize_caps_phrase`
    и документацию модуля).
    """
    return normalize_caps_phrase(value)


def normalize_organization_fields(org_data: Dict[str, Any]) -> Dict[str, Any]:
    """
    Копия реквизитов организации с нормализованной ДОЛЖНОСТЬЮ.

    Правится ровно одно поле — `director_position`: «ДИРЕКТОР» → «Директор».
    Остальные поля организации остаются как пришли из источника
    (`full_name`, `short_name`, `director_name`, `legal_address`,
    `actual_address`, `bank_name`).

    Почему только должность
    -----------------------
    Для наименования авторитетный источник — DaData (данные ЕГРЮЛ). Если у них
    «ООО "АВАТЭК"» капсом, значит, так и в реестре, и печатать в договоре
    «ООО "Аватэк"» нельзя: это уже другое наименование, а не оформление.
    Должность — другое дело: «ГЕНЕРАЛЬНЫЙ ДИРЕКТОР» у DaData не название
    чего-либо, а формат хранения поля, и в документе принято «Генеральный
    директор».

    Исходный словарь НЕ меняется: функция отдаёт копию, поэтому вызывающий
    код решает, что делать со значениями (сначала записать, потом
    показать — или наоборот).

    Поля, которых в словаре нет, не появляются: справочник принимает
    словари с разным набором ключей, и добавлять в них пустые строки
    значило бы менять данные на ходу.
    """
    if not isinstance(org_data, dict):
        return org_data

    result = dict(org_data)
    if "director_position" in result:
        result["director_position"] = normalize_position(result["director_position"])
    return result
