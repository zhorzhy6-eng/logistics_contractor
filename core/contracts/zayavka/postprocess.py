# -*- coding: utf-8 -*-
"""
Шаги постобработки листа заявки Хавалов (ЭТАП 3.1.E.A.3).

Здесь только объявление шагов: каждый — тонкая обёртка над своим методом
ZayavkaExcelGenerator, а состав и порядок конвейера задаёт его
postprocess_steps(). Логика — в самом генераторе, как у DOCX-типов
(core/contracts/arenda_ts/postprocess.py, logistiks_rus/postprocess.py):
шаг получает открытый ЛИСТ Excel, а не документ Word, и данные заявки.

Зачем нужна обрезка строк
-------------------------
Бланк рассчитан на 10 машин (10 строк данных), а в заявке их обычно
меньше; присланный заказчиком файл тоже приходит с запасом строк (в
образце их 6). Если ничего не делать, в готовом файле останется «хвост»
строк — пустых или с данными ПРЕЖНЕЙ заявки, а нижний блок сторон будет
стоять далеко под таблицей. Шаг приводит число строк к числу машин:
лишние удаляются, низ бланка поднимается вслед за таблицей, а строки ниже
(«Заказчик / Перевозчик», место под подписи, «ФИО, подпись, печать»)
занимают то же положение относительно конца таблицы, что и в образце.

Шаг не мешает генерации: если удалять нечего, он молча ничего не делает.
Ошибку шага гасит в warning сам генератор (ZayavkaExcelGenerator._trim_rows),
как это делает база DOCX-типов для своей постобработки.
"""

from core.contracts.base_generator import PostprocessStep


class TrimVehicleRowsStep(PostprocessStep):
    """
    Приведение числа строк таблицы к фактическому количеству машин.

    Удаляет строки таблицы ниже последней записанной машины и поднимает
    вслед за ними нижний блок. Границы таблицы и блока сторон берутся из
    самого листа (по заголовкам и подписям), а не из номеров строк
    эталона, поэтому шаг работает и на присланном файле с другой
    геометрией.
    """

    name = "trim_vehicle_rows"

    def apply(self, sheet, data) -> None:
        vehicles = (data or {}).get("vehicles") or []
        self.generator._trim_surplus_vehicle_rows(sheet, len(vehicles))


__all__ = ["TrimVehicleRowsStep"]
