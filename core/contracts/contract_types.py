# -*- coding: utf-8 -*-
"""
Константы типов договоров (Шаг 1 рефакторинга архитектуры контрактов).

Тип договора — строковый Enum: значения можно писать в БД, конфиги и
логи без дополнительных преобразований.

Ключи типов — технические идентификаторы, они не зависят от того, как тип
называется в интерфейсе: человекочитаемые названия живут в
``core/contracts/picker_order.py`` (публичное «Экспедиторство») и в
приватной части проекта (названия клиентских типов).

Клиентские типы (всё, кроме ``perevozka`` и служебного ``expediciya``)
реализованы в приватной части проекта. Здесь остаются только их ключи:
перечисление — часть публичного контракта ядра, по нему строится реестр,
а пакеты типов подключаются лениво и изолированно
(``core/contracts/registry.py``).
"""

from enum import Enum


class ContractType(str, Enum):
    """Типы договоров, которые умеет создавать приложение."""

    PEREVOZKA = "perevozka"
    """Договор-заявка на перевозку (рабочий тип; в UI — «Экспедиторство»)."""

    FORMIKA = "formika"
    """Приложение к генеральному договору перевозки (клиентский тип)."""

    LOGISTIKS_RUS = "logistiks_rus"
    """Приложение к генеральному договору экспедиции (клиентский тип)."""

    ARENDA_TS = "arenda_ts"
    """Договор аренды транспортного средства с экипажем (клиентский тип)."""

    EXPEDICIYA = "expediciya"
    """Экспедиторская заявка (служебный тип, в списке выбора не показывается)."""

    ZAYAVKA_EXCEL = "zayavka_excel"
    """Заявка на перевозку в Excel-формате (клиентский тип)."""


#: Тип по умолчанию: историческое поведение — все старые вызовы без
#: указания типа генерируют договор-заявку на перевозку.
DEFAULT_CONTRACT_TYPE = ContractType.PEREVOZKA


def normalize_contract_type(value) -> ContractType:
    """
    Приводит произвольное значение (None / ContractType / str) к ContractType.

    Неизвестная строка не падает здесь: решение (ошибка или fallback)
    принимает реестр — он знает, какие типы реально зарегистрированы.
    """
    if value is None:
        return DEFAULT_CONTRACT_TYPE
    if isinstance(value, ContractType):
        return value
    return ContractType(str(value).strip())
