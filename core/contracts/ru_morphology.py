# Склонение ФИО
# ─────────────────────────────────────────────────────────────

def genitive_fio(full_name: str, gender: str = "") -> str:
    """
    ФИО в родительном падеже: «Ахмедов Тимур Артурович» →
    «Ахмедова Тимура Артуровича».

    Разбор по словам: 3 слова — фамилия, имя, отчество; 2 слова —
    фамилия и имя (отчества нет); 1 слово — только фамилия. Пустая
    строка → пустая строка (в бланке не появится «None» и лишнего
    пробела).

    Род берётся из аргумента, а если он не передан — определяется по
    отчеству (`detect_gender`): фамилия и имя склоняются по-разному у
    мужчин и женщин («Иванова Мария» → «Ивановой Марии», но «Иванов
    Пётр» → «Иванова Петра»).

    Род не угадывается (одно слово, отчества нет) — склоняется только
    то, что можно склонить однозначно: «Хейгетян» останется
    «Хейгетян», а имя на «-а» — «Елены».
    """
    text = strip_ip_prefix(full_name)
    if not text:
        return ""

    parts = text.split()
    if not gender:
        gender = detect_gender(text)

    surname, name, patronymic = _split_fio(parts)

    result: List[str] = []
    if surname:
        result.append(_genitive_surname(surname, gender))
    if name:
        result.append(_genitive_name(name, gender, has_patronymic=bool(patronymic)))
    if patronymic:
        result.append(_genitive_patronymic(patronymic))

    # Хвост ФИО (четвёртое и дальше слово) остаётся как есть: это не имя,
    # а пометка из справочника, и склонять её нельзя.
    if len(parts) > 3:
        result.extend(parts[3:])

    return " ".join(result).strip()


def _split_fio(parts: List[str]):
    """Фамилия, имя, отчество из слов ФИО (отчества может не быть)."""
    surname = parts[0] if parts else ""
    name = parts[1] if len(parts) > 1 else ""
    patronymic = parts[2] if len(parts) > 2 else ""
    return surname, name, patronymic


def _genitive_surname(surname: str, gender: str) -> str:
    """
    Фамилия в родительном падеже.

    Дефисные фамилии склоняются ПО ЧАСТЯМ («Иванов-Петров» →
    «Иванова-Петрова»): это две фамилии, и обе подчиняются одним и тем
    же правилам. Несклоняемые фамилии (см.
    NON_INFLECTED_SURNAME_ENDINGS) возвращаются как есть — у мужчин и у
    женщин одинаково.
    """
    if "-" in surname:
        return "-".join(
            _genitive_surname(part, gender) for part in surname.split("-")
        )

    lower = surname.lower()

    # Несклоняемые: Шевченко, Хейгетян, Долгих, Кучук, Швили.
    for ending in NON_INFLECTED_SURNAME_ENDINGS:
        if lower.endswith(ending) and len(surname) > len(ending):
            return surname

    # Женские фамилии на «-ова/-ева/-ёва/-ина/-ына» → «-овой/-евой/…».
    # Проверяются ПЕРВЫМИ: окончание «-ова» длиннее, чем «-ов», и без
    # этого «Иванова» превратилась бы в «Ивановаа».
    if gender == "female":
        for ending in ("ова", "ева", "ёва", "ына", "ина"):
            if lower.endswith(ending):
                return surname[:-1] + "ой"

    # Мужские фамилии на «-ов/-ев/-ёв/-ин/-ын» → «-ова/-ева/-ёва/-ина».
    for ending in ("ов", "ев", "ёв", "ын", "ин"):
        if lower.endswith(ending):
            return surname + "а"

    # «-ский/-цкий/-ская/-цкая» → «-ского/-цкого/-ской/-цкой».
    if lower.endswith("ский") or lower.endswith("цкий"):
        return surname[:-2] + "ого"
    if lower.endswith("ская") or lower.endswith("цкая"):
        return surname[:-2] + "ой"

    # Фамилии на «-ая/-яя» (Красная, Синяя) → «-ой/-ей». Проверяются ДО
    # общего правила «гласная + а»: «Красная» — не «Краснаы».
    if lower.endswith("ая") and len(surname) > 3:
        return surname[:-2] + "ой"
    if lower.endswith("яя") and len(surname) > 3:
        return surname[:-2] + "ей"

    # Фамилия на гласную (кроме «-ая/-яя»): «Гоголь» → «Гоголя»,
    # «Ковалевская» уже обработана выше, «Дюма» у мужчины → «Дюмы» —
    # так же, как имя: после «г/к/х» пишется «-и», а не «-ы».
    if lower.endswith("а") and len(surname) > 1:
        return surname[:-1] + ("и" if lower[-2] in "гкх" else "ы")
    if lower.endswith("я") and len(surname) > 1:
        return surname[:-1] + "и"
    if lower.endswith("ь") and len(surname) > 1:
        return surname[:-1] + "я"

    # Мужская фамилия на согласную: «Пестряев» сюда не попадает
    # (сработало правило «-ев» выше), а «Смит» → «Смита».
    if gender == "male" and surname[-1].isalpha() \
            and surname[-1].lower() not in "аеёиоуыэюяйь":
        return surname + "а"

    return surname


def _genitive_name(name: str, gender: str, has_patronymic: bool = False) -> str:
    """
    Имя в родительном падеже.

    Правила: «-й» → «-я» (Андрей → Андрея), «-ь» → «-я» (Игорь → Игоря),
    «-ия» → «-ии» (Мария → Марии, Илья → Ильи), «-а» → «-ы» (Анна →
    Анны), после «г/к/х» — «-и» (Ольга → Ольги), «-я» → «-и» (Софья →
    Софьи), мужское на согласную → «+а» (Тимур → Тимура).

    Имя на «-ия» у МУЖЧИНЫ (Илия, Захария) склоняется так же, как
    женское, поэтому здесь нужен род: без отчества и без явного рода
    имя на «-ия» остаётся как есть.
    """
    lower = name.lower()

    if lower.endswith("ия"):
        # «Мария» → «Марии». Род неизвестен и отчества нет — не гадаем.
        if gender == "female" or has_patronymic:
            return name[:-1] + "и"
        return name

    # Мягкий знак и «й» — до гласных: «Игорь» → «Игоря», «Андрей» →
    # «Андрея» (окончание «-ей» здесь не при чём).
    if lower.endswith("ь"):
        return name[:-1] + "я"
    if lower.endswith("й"):
        return name[:-1] + "я"

    if lower.endswith("а"):
        return name[:-1] + ("и" if lower[-2] in "гкх" else "ы")
    if lower.endswith("я"):
        return name[:-1] + "и"

    # Мужское имя на согласную: «Тимур» → «Тимура».
    if gender == "male" and name[-1].isalpha() \
            and name[-1].lower() not in "аеёиоуыэюяйь":
        return name + "а"

    return name


def _genitive_patronymic(patronymic: str) -> str:
    """
    Отчество в родительном падеже: «-ович» → «-овича», «-овна» → «-овны».

    Отчество — самое надёжное слово ФИО: у него закрытый список
    окончаний, и правило срабатывает всегда, кроме экзотики. Незнакомое
    окончание («-ич» без «ов/ев») тоже обрабатывается.
    """
    lower = patronymic.lower()
    for ending, replacement in PATRONYMIC_ENDINGS:
        if lower.endswith(ending):
            return patronymic[: -len(ending)] + replacement

    if lower.endswith("ич"):
        return patronymic + "а"

    return patronymic
