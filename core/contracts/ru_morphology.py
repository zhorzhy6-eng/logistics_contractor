"""
Русская морфология для бланков: род ФИО, падеж должности и ФИО.

Зачем отдельный модуль
----------------------
Шаблоны договоров печатают сторону в косвенном падеже и в нужном роде:

  * п. 1.1 / 1.2 — «в лице директора Ахмедова Тимура Артуровича,
    действующего на основании Устава» (у женщины-директора —
    «действующей», у ИП — «именуемая» / «именуемый»);
  * у заказчика-ИП директора нет вовсе, и ФИО в п. 1.1 не печатается.

Раньше бланки печатали ИМЕНИТЕЛЬНЫЙ падеж и жёстко мужской род
(«в лице Генеральный директор Ахмедов Тимур Артурович, действующего»).
Падеж и род считает генератор — в одном месте, а не в трёх бланках;
здесь лежит сама морфология, без Qt, без docx и без доступа к базе,
поэтому её можно проверить тестами отдельно от документов.

Морфологического словаря (pymorphy) в проекте нет и не добавляется:
правила построены на окончаниях. Это не академическая морфология, а
рабочий инструмент для должностей и ФИО из справочника. Если правило
не подходит к конкретной фамилии — фамилия остаётся как есть: пусть
в договоре будет именительный падеж, чем испорченная фамилия.
"""

import re
from typing import List

__all__ = [
    "detect_gender",
    "pronoun_by_gender",
    "acting_by_gender",
    "genitive_position",
    "genitive_fio",
]

#: Приставки вида лица, которые справочник хранит вместе с ФИО
#: («Индивидуальный предприниматель Добросоцкий А.Н.»). Порядок важен:
#: длинная приставка проверяется первой, иначе от «ИП » остался бы хвост.
IP_PREFIXES = ("Индивидуальный предприниматель ", "ИП ")

#: Окончания женских отчеств.
FEMALE_PATRONYMIC_ENDINGS = ("овна", "евна", "ична", "инична")

#: Окончания фамилий, которые НЕ склоняются ни у мужчин, ни у женщин:
#: украинские (-ко, -енко, -ук, -юк), русские (-их, -ых), армянские (-ян),
#: грузинские (-швили, -дзе), а также фамилии на -аго/-яго.
#: Проверяются от длинных к коротким.
NON_INFLECTED_SURNAME_ENDINGS = (
    "енко", "швили", "инична", "дзе", "аго", "яго",
    "ко", "их", "ых", "ян", "ук", "юк",
)

#: Падежные окончания отчеств: (что менять, на что менять).
PATRONYMIC_ENDINGS = (
    ("инична", "иничны"),
    ("овна", "овны"),
    ("евна", "евны"),
    ("ична", "ичны"),
    ("ович", "овича"),
    ("евич", "евича"),
)


def strip_ip_prefix(full_name: str) -> str:
    """
    ФИО без приставки «ИП » / «Индивидуальный предприниматель ».

    Приставка — не часть имени, а вид лица; в бланке её печатает
    отдельный плейсхолдер ({{*_legal_form}}).
    """
    text = str(full_name or "").strip()
    lowered = text.lower()
    for prefix in IP_PREFIXES:
        if lowered.startswith(prefix.lower()):
            return text[len(prefix):].strip()
    return text


def detect_gender(full_name: str) -> str:
    """
    Пол по отчеству: «-овна/-евна/-ична/-инична» → female, иначе male.

    Отчество — третье слово ФИО. Приставка «ИП » и «Индивидуальный
    предприниматель » снимается до разбора: у ИП в справочнике
    наименование лежит целиком, и по номеру слова род тогда не
    угадывается.

    Отчества нет (или слов меньше трёх) → male: это форма по умолчанию
    в бланке. Пустая строка → male.
    """
    parts = strip_ip_prefix(full_name).split()
    if len(parts) >= 3:
        patronymic = parts[2].lower()
        if patronymic.endswith(FEMALE_PATRONYMIC_ENDINGS):
            return "female"
    return "male"


def pronoun_by_gender(gender: str) -> str:
    """
    Причастие «именуемый» / «именуемая» / «именуемое».

    У ООО — «именуемое» (средний род, организация), у ИП — по полу ФИО.
    Незнакомый пол → «именуемое» (нейтральная форма).
    """
    return {
        "male": "именуемый",
        "female": "именуемая",
    }.get(gender, "именуемое")


def acting_by_gender(gender: str) -> str:
    """
    Причастие «действующий» / «действующая» / «действующее».

    У ИП (действует сам) — по полу ФИО; у ООО — «действующее».
    Незнакомый пол → «действующее».
    """
    return {
        "male": "действующий",
        "female": "действующая",
    }.get(gender, "действующее")


